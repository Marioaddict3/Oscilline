std::string_view evidence_name(Evidence evidence) {
    switch (evidence) {
    case Evidence::Name:
        return "name";
    case Evidence::Format:
        return "format";
    case Evidence::Emulator:
        return "emulator";
    case Evidence::Visual:
        return "visual";
    }
    return "name";
}

