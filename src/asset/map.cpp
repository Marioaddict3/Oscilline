std::span<const MapRow> asset_map() {
    return kMap;
}

std::span<const ClipToken> character_clip_tokens() {
    return kClipTokens;
}

const MapRow* map_row(Slot slot) {
    for (const MapRow& row : kMap) {
        if (row.slot == slot) {
            return &row;
        }
    }
    return nullptr;
}

